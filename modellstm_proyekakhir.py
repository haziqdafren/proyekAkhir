# Identifikasi outliers
outliers_mask = (df['Revenue'] < lower_bound) | (df['Revenue'] > upper_bound)
outliers = df[outliers_mask].copy()

print(f"\n🔍 Outliers detected: {len(outliers)} hari")

if len(outliers) > 0:
    print("\n📋 Detail outliers:")
    print(outliers[['Tanggal', 'Revenue', 'Kamar_Terjual', 'Okupansi_Rate']].to_string(index=True))

# ===== CLEANING METHOD: INTERPOLATION =====
print("\n" + "=" * 80)
print("🔧 CLEANING METHOD: Interpolation")
print("=" * 80)

print("\nℹ️ Metode: Replace outlier dengan rata-rata hari sebelum & sesudah")
print("   Jika di awal/akhir dataset, gunakan median bulan tersebut\n")

# Sort by date untuk memastikan urutan benar
df = df.sort_values('Tanggal').reset_index(drop=True)

outliers_cleaned = []

for idx in outliers.index:
    old_value = df.loc[idx, 'Revenue']
    tanggal = df.loc[idx, 'Tanggal']
    tahun = df.loc[idx, 'Tahun']
    bulan = df.loc[idx, 'Bulan']

    # Method 1: Interpolation dari hari sebelum & sesudah
    if idx > 0 and idx < len(df) - 1:
        prev_value = df.loc[idx - 1, 'Revenue']
        next_value = df.loc[idx + 1, 'Revenue']

        # Check jika prev/next juga outlier, skip
        if prev_value > upper_bound or next_value > upper_bound:
            # Gunakan median bulan tersebut
            month_data = df[(df['Tahun'] == tahun) & (df['Bulan'] == bulan) &
                           (df['Revenue'] <= upper_bound)]['Revenue']
            new_value = month_data.median()
            method = "median_bulan"
        else:
            new_value = (prev_value + next_value) / 2
            method = "interpolation"
    else:
        # Di awal/akhir dataset, gunakan median bulan
        month_data = df[(df['Tahun'] == tahun) & (df['Bulan'] == bulan) &
                       (df['Revenue'] <= upper_bound)]['Revenue']
        new_value = month_data.median()
        method = "median_bulan"

    # Update value
    df.loc[idx, 'Revenue'] = new_value

    outliers_cleaned.append({
        'Tanggal': tanggal,
        'Old_Value': old_value,
        'New_Value': new_value,
        'Method': method,
        'Kamar_Terjual': df.loc[idx, 'Kamar_Terjual'],
        'Okupansi_Rate': df.loc[idx, 'Okupansi_Rate']
    })

# ===== REPORT CLEANING =====
if len(outliers_cleaned) > 0:
    print("✅ Cleaning completed!")
    print("\n📊 CLEANING REPORT:")
    df_cleaning = pd.DataFrame(outliers_cleaned)
    print(df_cleaning.to_string(index=False))

    print(f"\n💾 Total revenue cleaned:")
    print(f"   Before: Rp {df_cleaning['Old_Value'].sum():,.0f}")
    print(f"   After:  Rp {df_cleaning['New_Value'].sum():,.0f}")
    print(f"   Diff:   Rp {(df_cleaning['Old_Value'].sum() - df_cleaning['New_Value'].sum()):,.0f}")

