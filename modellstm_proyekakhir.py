from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

def calculate_metrics(y_true, y_pred, set_name):
    """
    Calculate comprehensive error metrics

    Returns MAE, RMSE, MAPE, R2 for each room type and overall
    """
    metrics = {}

    # Per room type metrics
    for i, room_type in enumerate(room_type_features):
        y_true_room = y_true[:, i]
        y_pred_room = y_pred[:, i]

        # MAE
        mae = mean_absolute_error(y_true_room, y_pred_room)

        # RMSE
        rmse = np.sqrt(mean_squared_error(y_true_room, y_pred_room))

        # MAPE (avoid division by zero)
        mape = np.mean(np.abs((y_true_room - y_pred_room) / np.maximum(y_true_room, 1))) * 100

        # R2
        r2 = r2_score(y_true_room, y_pred_room)

        metrics[room_type] = {
            'MAE': mae,
            'RMSE': rmse,
            'MAPE': mape,
            'R2': r2
        }

    # Overall metrics (averaged across all room types)
    mae_overall = mean_absolute_error(y_true.flatten(), y_pred.flatten())
    rmse_overall = np.sqrt(mean_squared_error(y_true.flatten(), y_pred.flatten()))

    # Overall MAPE (weighted by actual values)
    mape_overall = np.mean(np.abs((y_true - y_pred) / np.maximum(y_true, 1))) * 100

    # Overall R2
    r2_overall = r2_score(y_true.flatten(), y_pred.flatten())

    metrics['Overall'] = {
        'MAE': mae_overall,
        'RMSE': rmse_overall,
        'MAPE': mape_overall,
        'R2': r2_overall
    }

    return metrics

