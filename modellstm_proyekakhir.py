def build_lstm_model(config):
    """
    Build optimized LSTM for daily occupancy prediction

    Architecture:
    Input(30, 55) → LSTM(64, return_seq) → LSTM(32) → Dense(16) → Output(1)

    With dropout for regularization
    """

    # Input layer
    inputs = layers.Input(
        shape=(config['sequence_length'], config['n_features']),
        name='input_sequence'
    )

    # LSTM Layer 1 (return sequences for stacking)
    lstm1 = layers.LSTM(
        units=config['lstm_units_1'],
        return_sequences=True,
        dropout=config['dropout_rate'],
        recurrent_dropout=config['recurrent_dropout'],
        name='lstm_1'
    )(inputs)

    # LSTM Layer 2 (final LSTM, no return sequences)
    lstm2 = layers.LSTM(
        units=config['lstm_units_2'],
        return_sequences=False,
        dropout=config['dropout_rate'],
        recurrent_dropout=config['recurrent_dropout'],
        name='lstm_2'
    )(lstm1)

    # Dense layer (with ReLU activation)
    dense = layers.Dense(
        units=config['dense_units'],
        activation='relu',
        name='dense'
    )(lstm2)

    # Output layer (sigmoid to constrain [0,1])
    outputs = layers.Dense(
        units=config['n_outputs'],
        activation=config['output_activation'],
        name='output_occupancy_rate'
    )(dense)

    # Create model
    model = models.Model(
        inputs=inputs,
        outputs=outputs,
        name=config['model_name']
    )

    # Compile
    model.compile(
        optimizer=Adam(learning_rate=config['learning_rate']),
        loss=config['loss'],
        metrics=[
            'mae',
            RootMeanSquaredError(name='rmse'),
            MeanAbsolutePercentageError(name='mape')
        ]
    )

    return model

