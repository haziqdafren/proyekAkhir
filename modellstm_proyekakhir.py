print(f"   💡 Trade-off: -1 feature, +365 days of 2021 data!")

# ===== 5. ROLLING WINDOW FEATURES =====
print("\n5️⃣ Creating Rolling Window Features...")

df_daily['occ_ma_3'] = df_daily['Okupansi_Rate'].rolling(window=3, min_periods=1).mean()
df_daily['occ_ma_7'] = df_daily['Okupansi_Rate'].rolling(window=7, min_periods=1).mean()
df_daily['occ_ma_14'] = df_daily['Okupansi_Rate'].rolling(window=14, min_periods=1).mean()
df_daily['occ_ma_30'] = df_daily['Okupansi_Rate'].rolling(window=30, min_periods=1).mean()

df_daily['occ_std_7'] = df_daily['Okupansi_Rate'].rolling(window=7, min_periods=1).std()
df_daily['occ_std_30'] = df_daily['Okupansi_Rate'].rolling(window=30, min_periods=1).std()

df_daily['occ_min_7'] = df_daily['Okupansi_Rate'].rolling(window=7, min_periods=1).min()
df_daily['occ_max_7'] = df_daily['Okupansi_Rate'].rolling(window=7, min_periods=1).max()

df_daily['occ_ema_7'] = df_daily['Okupansi_Rate'].ewm(span=7, adjust=False).mean()
df_daily['occ_ema_30'] = df_daily['Okupansi_Rate'].ewm(span=30, adjust=False).mean()

