from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

def calculate_metrics(y_true, y_pred, set_name=""):
    """Calculate comprehensive evaluation metrics"""

    # Flatten arrays
    y_true = y_true.flatten()
    y_pred = y_pred.flatten()

    # Clip predictions to valid range [0, 100]
    y_pred = np.clip(y_pred, 0, 100)

    # MAE (in percentage points)
    mae = mean_absolute_error(y_true, y_pred)

    # RMSE (in percentage points)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))

    # MAPE (percentage)
    # Handle zero values to avoid division by zero
    mape = np.mean(np.abs((y_true - y_pred) / np.where(y_true == 0, 1, y_true))) * 100

    # R² Score
    r2 = r2_score(y_true, y_pred)

    # Directional Accuracy (trend prediction)
    if len(y_true) > 1:
        direction_true = np.diff(y_true) > 0
        direction_pred = np.diff(y_pred) > 0
        directional_acc = np.mean(direction_true == direction_pred) * 100
    else:
        directional_acc = 0

    # Additional metrics
    mean_error = np.mean(y_pred - y_true)  # Bias
    median_error = np.median(np.abs(y_pred - y_true))
    max_error = np.max(np.abs(y_pred - y_true))

    results = {
        'MAE': mae,
        'RMSE': rmse,
        'MAPE': mape,
        'R2': r2,
        'Directional_Accuracy': directional_acc,
        'Mean_Error': mean_error,
        'Median_Error': median_error,
        'Max_Error': max_error,
        'Mean_Actual': np.mean(y_true),
        'Mean_Predicted': np.mean(y_pred)
    }

    return results

