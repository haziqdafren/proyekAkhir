# ===== BUILD MODEL FUNCTION =====
def build_lstm_model(config):
    """
    Build Multi-Output LSTM Model

    Architecture:
    -------------
    Input(12, 9)
        → LSTM(64, return_sequences=True) + Dropout(0.2)
        → LSTM(32) + Dropout(0.2)
        → Dense(16, relu)
        → Output Dense(4, linear)

    Parameters:
    -----------
    config : dict
        Model configuration parameters

    Returns:
    --------
    model : keras.Model
        Compiled LSTM model
    """

    # Input layer
    inputs = layers.Input(
        shape=(config['sequence_length'], config['n_features']),
        name='input_sequence'
    )

    # LSTM Layer 1 (Stacked LSTM - return sequences)
    lstm1 = layers.LSTM(
        units=config['lstm_units_1'],
        return_sequences=True,  # Return sequences untuk stacked LSTM
        dropout=config['dropout_rate'],
        recurrent_dropout=config['recurrent_dropout'],
        name='lstm_layer_1'
    )(inputs)

    # LSTM Layer 2 (Final LSTM - no return sequences)
    lstm2 = layers.LSTM(
        units=config['lstm_units_2'],
        return_sequences=False,  # Output only last timestep
        dropout=config['dropout_rate'],
        recurrent_dropout=config['recurrent_dropout'],
        name='lstm_layer_2'
    )(lstm1)

    # Dense layer untuk feature extraction
    dense = layers.Dense(
        units=config['dense_units'],
        activation='relu',
        name='dense_features'
    )(lstm2)

    # Output layer - Multi-output (4 room types)
    outputs = layers.Dense(
        units=config['n_targets'],
        activation=config['output_activation'],
        name='output_room_types'
    )(dense)

    # Create model
    model = models.Model(inputs=inputs, outputs=outputs, name='Multi_Output_LSTM')

    # Compile model
    model.compile(
        optimizer=Adam(learning_rate=config['learning_rate']),
        loss=config['loss'],
        metrics=config['metrics']
    )

    return model

