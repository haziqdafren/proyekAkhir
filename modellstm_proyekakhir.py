# Create dummy arrays for inverse transform (scaler expects all 7 features)
def denormalize_room_types(normalized_preds, scaler, room_type_indices):
    """
    Denormalize hanya room type predictions

    Parameters:
    -----------
    normalized_preds : array (n_samples, 4)
        Normalized predictions untuk 4 room types
    scaler : MinMaxScaler
        Fitted scaler
    room_type_indices : list
        Indices of room types in scaler features

    Returns:
    --------
    denormalized : array (n_samples, 4)
        Denormalized predictions dalam skala asli (room counts)
    """
    n_samples = normalized_preds.shape[0]
    n_scaler_features = len(features_to_normalize)  # 7

    # Create dummy array dengan semua features
    dummy = np.zeros((n_samples, n_scaler_features))

    # Fill room type values
    for i, idx in enumerate(room_type_indices):
        dummy[:, idx] = normalized_preds[:, i]

    # Inverse transform
    denormalized_full = scaler.inverse_transform(dummy)

    # Extract hanya room types
    denormalized = denormalized_full[:, room_type_indices]

    return denormalized

