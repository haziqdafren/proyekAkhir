df_daily['DayOfYear'] = df_daily['Tanggal'].dt.dayofyear
df_daily['WeekOfYear'] = df_daily['Tanggal'].dt.isocalendar().week.astype(int)
df_daily['Quarter'] = df_daily['Tanggal'].dt.quarter
df_daily['DayName'] = df_daily['Tanggal'].dt.day_name()

# Binary flags
df_daily['is_weekend'] = (df_daily['DayOfWeek'] >= 5).astype(int)
df_daily['is_monday'] = (df_daily['DayOfWeek'] == 0).astype(int)
df_daily['is_friday'] = (df_daily['DayOfWeek'] == 4).astype(int)

# Month flags
df_daily['is_january'] = (df_daily['Month'] == 1).astype(int)
df_daily['is_march'] = (df_daily['Month'] == 3).astype(int)
df_daily['is_may'] = (df_daily['Month'] == 5).astype(int)
df_daily['is_july'] = (df_daily['Month'] == 7).astype(int)
df_daily['is_august'] = (df_daily['Month'] == 8).astype(int)
df_daily['is_december'] = (df_daily['Month'] == 12).astype(int)

# Cyclical encoding
df_daily['month_sin'] = np.sin(2 * np.pi * df_daily['Month'] / 12)
df_daily['month_cos'] = np.cos(2 * np.pi * df_daily['Month'] / 12)
df_daily['dow_sin'] = np.sin(2 * np.pi * df_daily['DayOfWeek'] / 7)
df_daily['dow_cos'] = np.cos(2 * np.pi * df_daily['DayOfWeek'] / 7)
df_daily['doy_sin'] = np.sin(2 * np.pi * df_daily['DayOfYear'] / 365)
df_daily['doy_cos'] = np.cos(2 * np.pi * df_daily['DayOfYear'] / 365)

print(f"   ✅ Created 20 temporal features")

# ===== 2. HOLIDAY FEATURES =====
print("\n2️⃣ Creating Holiday Features...")

holidays = pd.to_datetime([
    '2021-01-01', '2021-02-12', '2021-03-11', '2021-05-13', '2021-05-26',
    '2021-08-17', '2021-12-25',
    '2022-01-01', '2022-02-01', '2022-05-02', '2022-05-03', '2022-05-16',
    '2022-08-17', '2022-12-25',
    '2023-01-01', '2023-01-22', '2023-04-22', '2023-04-23', '2023-05-18',
    '2023-08-17', '2023-12-25',
    '2024-01-01', '2024-02-10', '2024-03-11', '2024-04-10', '2024-05-09',
    '2024-05-23', '2024-08-17', '2024-12-25',
    '2025-01-01', '2025-03-31', '2025-05-01', '2025-05-12', '2025-08-17',
    '2025-12-25'
])

df_daily['is_holiday'] = df_daily['Tanggal'].isin(holidays).astype(int)

def days_to_holiday(date, holidays):
    future = holidays[holidays > date]
    return (future.min() - date).days if len(future) > 0 else 365

def days_from_holiday(date, holidays):
    past = holidays[holidays < date]
    return (date - past.max()).days if len(past) > 0 else 365

df_daily['days_to_holiday'] = df_daily['Tanggal'].apply(lambda x: days_to_holiday(x, holidays))
df_daily['days_from_holiday'] = df_daily['Tanggal'].apply(lambda x: days_from_holiday(x, holidays))
df_daily['is_holiday_window'] = (
    (df_daily['days_to_holiday'] <= 3) |
    (df_daily['days_from_holiday'] <= 3)
).astype(int)

print(f"   ✅ Created 4 holiday features")

# ===== 3. BUSINESS FEATURES =====
print("\n3️⃣ Creating Business Features...")

df_daily['is_payday'] = df_daily['Day'].isin([25, 26, 27, 28, 29, 30, 31, 1, 2, 3]).astype(int)
df_daily['is_month_end'] = (df_daily['Day'] >= 25).astype(int)
df_daily['is_month_start'] = (df_daily['Day'] <= 5).astype(int)
df_daily['weekend_holiday'] = df_daily['is_weekend'] * df_daily['is_holiday']
df_daily['weekend_payday'] = df_daily['is_weekend'] * df_daily['is_payday']

print(f"   ✅ Created 5 business features")

# ===== 4. LAG FEATURES (WITHOUT lag_365!) =====
print("\n4️⃣ Creating Lag Features (WITHOUT lag_365 to preserve 2021 data)...")

# Short-term lags
df_daily['occ_lag_1'] = df_daily['Okupansi_Rate'].shift(1)
df_daily['occ_lag_2'] = df_daily['Okupansi_Rate'].shift(2)
df_daily['occ_lag_3'] = df_daily['Okupansi_Rate'].shift(3)

# Weekly lags
df_daily['occ_lag_7'] = df_daily['Okupansi_Rate'].shift(7)
df_daily['occ_lag_14'] = df_daily['Okupansi_Rate'].shift(14)

# Monthly lags
df_daily['occ_lag_30'] = df_daily['Okupansi_Rate'].shift(30)
df_daily['occ_lag_60'] = df_daily['Okupansi_Rate'].shift(60)

# ⚠️ REMOVED: occ_lag_365 to preserve 2021 data!
