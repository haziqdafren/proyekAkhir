def calculate_md5(filepath, chunk_size=8192):
    """
    Hitung MD5 hash dari file dengan membaca chunk by chunk.
    Metode ini efisien untuk file berukuran besar (ratusan MB).

    Args:
        filepath: Path lengkap ke file
        chunk_size: Ukuran chunk untuk dibaca (default 8KB)

    Returns:
        MD5 hash string (32 karakter hexadecimal)
    """
    md5 = hashlib.md5()
    with open(filepath, 'rb') as f:
        while True:
            chunk = f.read(chunk_size)
            if not chunk:
                break
            md5.update(chunk)
    return md5.hexdigest()


