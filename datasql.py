# Step 1: Extract column names dari INSERT statement
def extract_column_names(filepath, table_name='room_transaction'):
    """
    Extract nama kolom yang digunakan di INSERT statement.

    Args:
        filepath: Path ke file SQL
        table_name: Nama tabel yang akan di-parse

    Returns:
        List of column names
    """
    print(f"\nðŸ” Extracting column names from INSERT statement...")

    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        for line in f:
            if f'INSERT INTO `{table_name}`' in line:
                # Extract kolom dari pattern: INSERT INTO `table` (`col1`,`col2`,...)
                cols_match = re.search(r'INSERT INTO `' + table_name + r'`\s*\(([^)]+)\)', line)
                if cols_match:
                    cols_text = cols_match.group(1)
                    # Extract nama kolom (remove backticks)
                    column_names = [col.strip().strip('`') for col in cols_text.split(',')]
                    print(f"   âœ… Found {len(column_names)} columns in INSERT statement")
                    return column_names

    print("   âš ï¸ Could not find column names in INSERT statement")
    return None

# Step 2: Parse SQL INSERT statements
def parse_sql_inserts(filepath, table_name='room_transaction'):
    """
    Parse INSERT statements dari file SQL dan convert ke list of tuples.

    Args:
        filepath: Path ke file SQL
        table_name: Nama tabel yang akan di-parse

    Returns:
        Tuple: (list of data rows, number of columns)
    """
    data_rows = []
    num_columns = None

    print(f"\nâ³ Reading file: {os.path.basename(filepath)}")
    print("   Parsing INSERT statements...\n")

    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        current_insert = None
        line_count = 0

        for line in f:
            line_count += 1

            # Cari baris INSERT INTO
            if f'INSERT INTO `{table_name}`' in line:
                current_insert = line.strip()
                continue

            # Jika sedang membaca INSERT statement
            if current_insert:
                current_insert += ' ' + line.strip()

                # Cek apakah INSERT statement sudah selesai (diakhiri dengan ;)
                if line.strip().endswith(';'):
                    # Extract values menggunakan regex
                    # Pattern: VALUES (...),(...),(...)...;
                    values_section = re.search(r'VALUES\s+(.+);', current_insert)
                    if values_section:
                        values_text = values_section.group(1)

                        # Split by '),(' untuk pisahkan setiap row
                        rows = re.findall(r'\(([^)]+)\)', values_text)

                        for row in rows:
                            # Parse setiap field dalam row
                            # Handle NULL, string dengan quotes, dan numeric values
                            fields = []
                            current_field = ''
                            in_quotes = False

                            for char in row + ',':
                                if char == "'" and (not current_field or current_field[-1] != '\\'):
                                    in_quotes = not in_quotes
                                elif char == ',' and not in_quotes:
                                    field = current_field.strip()
                                    if field == 'NULL':
                                        fields.append(None)
                                    elif field.startswith("'") and field.endswith("'"):
                                        fields.append(field[1:-1])
                                    else:
                                        try:
                                            # Try convert to number
                                            if '.' in field:
                                                fields.append(float(field))
                                            else:
                                                fields.append(int(field))
                                        except:
                                            fields.append(field)
                                    current_field = ''
                                else:
                                    current_field += char

                            data_rows.append(tuple(fields))

                            # Get number of columns from first row
                            if num_columns is None:
                                num_columns = len(fields)

                    current_insert = None

            # Progress indicator setiap 100K baris
            if line_count % 100000 == 0:
                print(f"   Processed {line_count:,} lines... ({len(data_rows):,} data rows extracted)")

    print(f"\nâœ… Parsing complete!")
    print(f"   Total lines processed: {line_count:,}")
    print(f"   Total data rows extracted: {len(data_rows):,}")
    print(f"   Number of columns per row: {num_columns}")

    return data_rows, num_columns

